export type TKey = keyof typeof dict.en;

type Ctx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey) => string;
};

const LangCtx = createContext<Ctx | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const saved = typeof window !== "undefined" ? window.localStorage.getItem("mr-lang") : null;
    if (saved === "en" || saved === "hi" || saved === "te") setLangState(saved);
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") window.localStorage.setItem("mr-lang", l);
    if (typeof document !== "undefined") document.documentElement.lang = l;
    window.dispatchEvent(new CustomEvent("mr-lang-change", { detail: l }));
  };

  const t = (k: TKey) => {
    const langDict = dict[lang] as Record<string, string>;
    const enDict = dict.en as Record<string, string>;
    return langDict[k] ?? enDict[k] ?? (k as string);
  };

  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>;
}

export function useLang() {
  const ctx = useContext(LangCtx);
  if (!ctx) throw new Error("useLang must be used within LanguageProvider");
  return ctx;
}

